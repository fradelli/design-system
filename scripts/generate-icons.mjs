import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const dependencyFile = fileURLToPath(import.meta.resolve("@phosphor-icons/react/package.json"));
const dependencyRoot = dirname(dependencyFile);
const dependency = JSON.parse(await readFile(dependencyFile, "utf8"));
const ownPackage = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

if (ownPackage.dependencies[dependency.name] !== dependency.version) {
  throw new Error("Install the exact declared Phosphor version before generating icons.");
}

const names = (await readdir(join(dependencyRoot, "dist/ssr")))
  .filter((file) => file.endsWith(".es.js") && file !== "index.es.js")
  .map((file) => file.slice(0, -6))
  .sort();
const icons = [];
for (const name of names) {
  if (!/^[A-Z][A-Za-z0-9]*$/u.test(name)) throw new Error(`Invalid icon module: ${name}`);
  const exportName = `${name}Icon`;
  const module = `@phosphor-icons/react/dist/ssr/${name}`;
  const runtime = await import(module);
  if (!runtime[exportName] || runtime[exportName].displayName !== exportName) {
    throw new Error(`The canonical SSR component ${exportName} was not found in ${module}.`);
  }
  icons.push({ name, exportName, module });
}
if (!icons.length) throw new Error("The installed Phosphor catalog is empty.");

const catalog = {
  schemaVersion: 1,
  dependency: dependency.name,
  version: dependency.version,
  icons,
};
const header = "// Generated by scripts/generate-icons.mjs. Do not edit manually.\n";
const outputs = new Map([
  ["src/icons/catalog.json", `${JSON.stringify(catalog, null, 2)}\n`],
  [
    "src/icons/index.tsx",
    await format(
      `${header}export type { IconProps } from "./icon.types.js";\n` +
        icons
          .map(({ name, exportName }) => `export { ${exportName} } from "./generated/${name}.js";`)
          .join("\n"),
      { parser: "typescript", printWidth: 100 },
    ),
  ],
]);
for (const { name, exportName, module } of icons) {
  outputs.set(
    `src/icons/generated/${name}.tsx`,
    await format(
      `${header}import { ${exportName} as PhosphorIcon } from "${module}";\n` +
        'import type { IconProps } from "../icon.types.js";\n' +
        `export function ${exportName}(props: IconProps) { return <PhosphorIcon {...props} />; }\n`,
      { parser: "typescript", printWidth: 100 },
    ),
  );
}

const generatedDirectory = join(root, "src/icons/generated");
if (!check) await mkdir(generatedDirectory, { recursive: true });
const expectedFiles = new Set(icons.map(({ name }) => `${name}.tsx`));
for (const file of await readdir(generatedDirectory)) {
  if (!expectedFiles.has(file)) {
    throw new Error(`Unexpected generated icon: ${file}. Review catalog removals explicitly.`);
  }
}
for (const [path, expected] of outputs) {
  const target = join(root, path);
  if (check) {
    const actual = await readFile(target, "utf8").catch(() => null);
    if (actual?.replaceAll("\r\n", "\n") !== expected) {
      throw new Error(`${path} is stale. Run npm run icons:generate and review the catalog diff.`);
    }
  } else {
    await writeFile(target, expected);
  }
}
console.log(
  `${check ? "Verified" : "Generated"} ${icons.length} SSR icons from Phosphor ${dependency.version}.`,
);
